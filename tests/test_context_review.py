def test_handoffs_learnings_memory_and_store(fx):
    run(fx, "run")
    s = summary(fx)
    ho = {h["project"]: h for h in s["handoffs"]}
    assert ho["-proj"]["stale"] is True and ho["-fresh"]["stale"] is False
    assert s["nudge"]["stale_handoffs"] == 1
    glob_l, repo_l = s["learnings"]
    assert glob_l["section"] is False
    assert (repo_l["entries"], len(repo_l["past_two_weeks"])) == (2, 1)
    assert repo_l["oldest"] == (TODAY - timedelta(days=30)).isoformat()
    assert [m["entries"] for m in s["memory"]] == [3]
