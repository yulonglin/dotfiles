CMD = Path(__file__).resolve().parent.parent / "custom_bins" / "context-review"
TODAY = date(2026, 12, 1)

_loader = importlib.machinery.SourceFileLoader("context_review", str(CMD))
_spec = importlib.util.spec_from_loader(_loader.name, _loader)
cr = importlib.util.module_from_spec(_spec)
_loader.exec_module(cr)


def write(p: Path, text: str) -> Path:
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)
    return p


def git(repo: Path, *args: str, when: str) -> None:
    env = dict(os.environ, GIT_AUTHOR_DATE=f"{when}T12:00:00", GIT_COMMITTER_DATE=f"{when}T12:00:00",
               GIT_AUTHOR_NAME="t", GIT_AUTHOR_EMAIL="t@example.com",
               GIT_COMMITTER_NAME="t", GIT_COMMITTER_EMAIL="t@example.com")
    # No signing and no hooks: the fixture must not depend on this box's git config.
    r = subprocess.run(["git", "-C", str(repo), "-c", "commit.gpgsign=false",
                        "-c", "core.hooksPath=/dev/null", *args],
                       capture_output=True, text=True, env=env)
    assert r.returncode == 0, f"git {' '.join(args)}: {r.stderr}"


def skill(name: str, desc_block: str) -> str:
    return f"---\nname: {name}\n{desc_block}\n---\n\n# {name}\n\nBody.\n"


def tool_use(ts: str, tool: str, inp: dict, tid: str) -> str:
    return json.dumps({"type": "assistant", "timestamp": ts, "message": {"content": [
        {"type": "tool_use", "id": tid, "name": tool, "input": inp}]}})


def days_ago(n: int) -> str:
    return f"{(TODAY - timedelta(days=n)).isoformat()}T10:00:00.000Z"


def set_mtime(p: Path, d: date) -> None:
    t = datetime.combine(d, datetime.min.time()).timestamp() + 3600
    os.utime(p, (t, t))


