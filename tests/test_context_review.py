def test_run_is_read_only_outside_its_own_outputs(fx):
    before = snapshot(fx["repo"], fx["home"])
    assert run(fx, "run").returncode == 0
    assert snapshot(fx["repo"], fx["home"]) == before


def test_second_run_reports_deltas(fx):
    run(fx, "run")
    (fx["repo"] / "claude/rules/two.md").write_text("rule two\n" + "x" * 99 + "\n")
    later = TODAY + timedelta(days=31)
    assert run(fx, "run", today=later).returncode == 0
    s = summary(fx, later)
    assert s["previous"] == TODAY.isoformat()
    assert s["always_on"]["delta_bytes"] == 100
    assert s["nudge"]["always_on_delta_bytes"] == 100


def test_status_and_ack(fx):
    r = run(fx, "status")
    assert r.returncode == 1 and "no run" in r.stdout
    run(fx, "run")
    r = run(fx, "status")
    assert r.returncode == 0 and "not yet reviewed" in r.stdout and TODAY.isoformat() in r.stdout
    assert run(fx, "ack", "--note", "kept all").returncode == 0
    ack = json.loads((fx["state"] / TODAY.isoformat() / "acknowledged.json").read_text())
    assert ack["note"] == "kept all"
    assert "acknowledged" in run(fx, "status").stdout


def test_vault_failure_exits_3_and_is_recorded(fx):
    blocker = write(fx["tmp"] / "not-a-dir", "x")
    r = run(fx, "run", vault=blocker / "sub")
    assert r.returncode == 3
    s = summary(fx)
    assert s["vault_copy"]["status"].startswith("error")
    assert (fx["state"] / TODAY.isoformat() / "report.md").is_file()


