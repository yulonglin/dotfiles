"""Tests for custom_bins/context-review on a temp fixture.

The fixture is a fake dotfiles repo with real git history, a fake ~/.claude
(settings, plugin cache, transcripts, auto-memory) and a fake ~/.remember. Every
root is passed as a flag and HOME points into the fixture, so nothing here reads
or writes the real home.

It is built to hit the three traps the context-ledger README names, plus the two
this command adds:

- enabled != installed: a plugin in the cache but off in enabledPlugins costs nothing;
- renames hide usage: a backdated `git mv` must carry usage of the old name, and
  keep the original add date so the renamed skill is not exempted as new;
- folded YAML: a `description: >-` over several lines must not parse to empty;
- forks copy history: the same tool_use id in two files counts once;
- quoting is not invoking: a transcript line that merely mentions a skill in a
  tool result must not count.

Run: pytest tests/test_context_review.py
"""

