@pytest.mark.parametrize("block,want", [
    ("description: >-\n  a\n  b\n\n  c", "a b\nc"),
    ("description: |\n  a\n  b", "a\nb"),
    ("description: 'it''s'", "it's"),
    ('description: "a \\"q\\" b"', 'a "q" b'),
    ("description: plain # comment", "plain"),
])
def test_parse_frontmatter_shapes(block, want):
    assert cr.parse_frontmatter(f"---\nname: x\n{block}\n---\nbody")["description"] == want
