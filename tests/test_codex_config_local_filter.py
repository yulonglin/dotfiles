def run(args, stdin, env=None, cwd=None):
    return subprocess.run(
        [sys.executable, str(FILTER), *args], input=stdin.encode(), capture_output=True,
        env=env, cwd=cwd, check=True,
    ).stdout.decode()


@pytest.fixture
def env(tmp_path):
    e = dict(os.environ)
    e["XDG_STATE_HOME"] = str(tmp_path / "state")
    e["CODEX_HOME"] = str(tmp_path / "codex-home")
    return e


def state(env):
    return Path(env["XDG_STATE_HOME"]) / "codex-config-filter" / "local-tables.toml"


def test_clean_strips_machine_local_tables(env):
    out = run(["--clean"], CONFIG, env)
    d = tomllib.loads(out)
    assert set(d) == {"model", "model_reasoning_effort", "approval_policy", "mcp_servers",
                      "marketplaces", "plugins", "hooks", "memories"}
    assert set(d["mcp_servers"]) == {"context7"}
    assert set(d["marketplaces"]) == {"shared-git"}
    assert d["marketplaces"]["shared-git"] == {"source_type": "git", "source": "https://example.com/plugins.git"}
    assert list(d["hooks"]["state"]) == ["core@shared-git:hooks/hooks.json:session_start:0:0"]
    assert "/Users/" not in out
    assert "# Approve for me" in out and "# END SHARED MCP SERVERS" in out


def test_clean_is_idempotent(env):
    once = run(["--clean"], CONFIG, env)
    assert run(["--clean"], once, env) == once


@pytest.mark.parametrize("bad", ['model = "unterminated\n', '[[profiles]]\nname = "a"\n[projects."/x"]\ntrust_level = "trusted"\n'])
def test_clean_passes_through_what_it_does_not_understand(env, bad):
    assert run(["--clean"], bad, env) == bad


def test_clean_saves_state_only_for_the_live_file(env, tmp_path):
    run(["--clean", "codex/config.toml"], CONFIG, env, cwd=tmp_path)
    assert not state(env).exists()  # cwd/codex/config.toml is not $CODEX_HOME/config.toml
    home = Path(env["CODEX_HOME"])
    home.mkdir()
    (home / "config.toml").write_text(CONFIG)
    run(["--clean", "config.toml"], CONFIG, env, cwd=home)
    saved = tomllib.loads(state(env).read_text())
    assert "/Users/someone/code/secret-project" in saved["projects"]
    assert set(saved["marketplaces"]) == {"bundled"}


def test_clean_never_replaces_saved_tables_with_nothing(env):
    home = Path(env["CODEX_HOME"])
    home.mkdir()
    (home / "config.toml").write_text(CONFIG)
    run(["--save"], "", env)
    before = state(env).read_text()
    bare = run(["--clean"], CONFIG, env)
    run(["--clean", "config.toml"], bare, env, cwd=home)
    assert state(env).read_text() == before


def test_smudge_appends_saved_tables(env):
    home = Path(env["CODEX_HOME"])
    home.mkdir()
    (home / "config.toml").write_text(CONFIG)
    run(["--save"], "", env)
    blob = run(["--clean"], CONFIG, env)
    full = tomllib.loads(run(["--smudge"], blob, env))
    want = tomllib.loads(CONFIG)
    for m in want["marketplaces"].values():
        m.pop("last_updated", None)
        m.pop("last_revision", None)
    assert full == want


def test_smudge_passes_blob_through_on_conflict_or_no_state(env):
    blob = run(["--clean"], CONFIG, env)
    assert run(["--smudge"], blob, env) == blob  # nothing saved yet
    state(env).parent.mkdir(parents=True)
    state(env).write_text('[memories]\nuse_memories = false\n')  # duplicates a blob table
    assert run(["--smudge"], blob, env) == blob


def test_git_round_trip_keeps_local_tables_out_of_the_blob(env, tmp_path):
    repo = tmp_path / "repo"
    (repo / "scripts" / "git-filters").mkdir(parents=True)
    shutil.copy(FILTER, repo / "scripts" / "git-filters" / "codex-config-local")
    (repo / ".gitattributes").write_text("codex/config.toml filter=codex-local\n")
    home = repo / "codex"  # the live file is the tracked file, as with the ~/.codex symlink
    home.mkdir()
    (home / "config.toml").write_text(CONFIG)
    env = {**env, "CODEX_HOME": str(home), "GIT_CONFIG_GLOBAL": "/dev/null", "GIT_CONFIG_NOSYSTEM": "1"}

    def git(*a):
        return subprocess.run(["git", *a], cwd=repo, env=env, check=True, capture_output=True, text=True).stdout

    git("init", "-q")
    git("config", "user.email", "t@example.com")
    git("config", "user.name", "t")
    git("config", "filter.codex-local.clean", f"{sys.executable} scripts/git-filters/codex-config-local --clean %f")
    git("config", "filter.codex-local.smudge", f"{sys.executable} scripts/git-filters/codex-config-local --smudge")
    git("add", ".")
    git("commit", "-qm", "init")
    blob = git("show", "HEAD:codex/config.toml")
    assert "projects" not in tomllib.loads(blob) and "/Users/" not in blob
    assert git("status", "--porcelain") == ""

    (home / "config.toml").unlink()  # a pull that rewrites the file checks it out through smudge
    git("checkout", "--", "codex/config.toml")
    assert "/Users/someone/code/secret-project" in tomllib.loads((home / "config.toml").read_text())["projects"]
    assert git("status", "--porcelain") == ""


@pytest.mark.skipif(not Path("/usr/bin/python3").exists(), reason="no system python")
def test_old_python_reexecs_or_passes_through(env):
    r = subprocess.run(["/usr/bin/python3", str(FILTER), "--clean"], input=CONFIG.encode(),
                       capture_output=True, env=env, check=True)
    out = r.stdout.decode()
    assert out == CONFIG or "/Users/someone/code/secret-project" not in out
